import WebSocket from 'ws';
const mk=(name)=>new Promise(r=>{const ws=new WebSocket('ws://localhost:3055');const st={cards:{},zones:{},err:[]};ws.on('open',()=>ws.send(JSON.stringify({t:'join',room:'U',cid:name,name})));
ws.on('message',d=>{const m=JSON.parse(d);if(m.t==='welcome')st.you=m.you;if(m.t==='error')st.err.push(m.msg);if(m.t==='delta'){for(const[k,v]of Object.entries(m.cards||{}))v?st.cards[k]=v:delete st.cards[k];Object.assign(st.zones,m.zones||{});}});
st.send=(a,o={})=>ws.send(JSON.stringify({t:'act',a,...o}));setTimeout(()=>r(st),300)});
const sl=ms=>new Promise(r=>setTimeout(r,ms));
const meta={a:{name:'Bear',faces:[{name:'Bear',type:'Creature — Bear',text:'',power:'2',toughness:'2'}]}};
const A=await mk('A'),B=await mk('B');
A.send('loadDeck',{entries:[{sid:'a',qty:20}],meta});await sl(200);
const hand=()=>A.zones[A.you+':hand'].length;
console.log('hand',hand());
A.send('draw',{n:2});await sl(150);console.log('after draw',hand());
A.send('undo');await sl(150);console.log('after undo',hand(),'lib',A.zones[A.you+':library'].n);
A.send('undo');await sl(150);console.log('undo loadDeck -> cards',Object.keys(A.cards).length,'lib',A.zones[A.you+':library']?.n);
A.send('loadDeck',{entries:[{sid:'a',qty:20}],meta});await sl(200);
B.send('draw');await sl(100);A.send('undo');await sl(150);console.log('A undo after B acted ->',A.err.at(-1));
B.send('undo');await sl(150);
A.send('token',{meta:{sid:'t',name:'Goblin',faces:[{name:'Goblin',type:'Token Creature',power:'1',toughness:'1',text:''}]},n:4});await sl(150);
const t=Object.values(A.cards).filter(c=>c.token);console.log('tokens',t.length,'dx',(t[3].x-t[0].x).toFixed(3));
A.send('spread',{ids:t.map(c=>c.id)});await sl(150);console.log('spread dx',(A.cards[t[3].id].x-A.cards[t[0].id].x).toFixed(3));
A.send('undo');await sl(150);console.log('undo spread dx',(A.cards[t[3].id].x-A.cards[t[0].id].x).toFixed(3));
process.exit(0);
