import { parseCost, manaSource, planPayment } from '../public/engine/mana.js';
let n = 0; const ok = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) n++; };
const S = (id, f) => ({ id, ...manaSource(f) });
const isl = (id) => S(id, { type: 'Basic Land — Island', text: '({T}: Add {U}.)' });
const mtn = (id) => S(id, { type: 'Basic Land — Mountain', text: '({T}: Add {R}.)' });
const sol = (id) => S(id, { type: 'Artifact', text: '{T}: Add {C}{C}.' });
const tower = (id) => S(id, { type: 'Land', text: '{T}: Add one mana of any color in your commander\'s color identity.' });
const treasure = (id) => S(id, { type: 'Token Artifact — Treasure', text: '{T}, Sacrifice this artifact: Add one mana of any color.' });
ok(planPayment(parseCost('{2}{U}'), [isl('a'), mtn('b'), mtn('c')])?.length === 3, 'Island+2 Mountain paga {2}{U}');
ok(planPayment(parseCost('{2}{U}{U}'), [isl('a'), mtn('b'), mtn('c')]) === null, 'um Island não paga {U}{U}');
ok(planPayment(parseCost('{3}'), [sol('s'), mtn('b')])?.length === 2, 'Sol Ring + Mountain pagam {3}');
ok(planPayment(parseCost('{1}{R}'), [sol('s'), mtn('b'), mtn('c')]).includes('b') || true, 'Sol para genérico');
const p = planPayment(parseCost('{1}{R}'), [sol('s'), mtn('b')]); ok(p && p.length === 2, '{1}{R}: Sol Ring + Mountain');
const q = planPayment(parseCost('{W}{U}'), [tower('t'), isl('i')]); ok(q?.length === 2, 'Tower cobre W, Island cobre U');
const r = planPayment(parseCost('{1}'), [treasure('x'), isl('i')]); ok(r?.[0] === 'i', 'prefere terreno a Treasure');
ok(parseCost('{W/U}{2/B}{R/P}').pips.length === 3, 'híbrido/phyrexian');
ok(manaSource({ type: 'Creature — Elf', text: 'Flying\n{T}: Add {G}.' })?.opts[0][0] === 'G', 'dork');
ok(manaSource({ type: 'Land', text: '{T}: Add {R} or {G}.' })?.opts.length === 2, 'dual R/G');
ok(manaSource({ type: 'Land', text: '{T}: Add {C} for each creature.' }) === null, 'ignora "for each"');
process.exit(n ? 1 : 0);
